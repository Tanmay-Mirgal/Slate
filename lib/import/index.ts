import { normalizeGraph, type Graph } from "../diagram/graph";
import { parseComposeDocument, composeToImport } from "./compose";
import { looksLikeSql, sqlToImport } from "./sql";
import { looksLikeTree, treeToImport } from "./tree";
import { code, table, type DetectedKind, type ImportResult } from "./types";

export type { DetectedKind, ImportResult } from "./types";
export { MAX_SOURCE_CHARS } from "./types";

/** Which deterministic importer (if any) understands this text. Cheap enough to call on every keystroke. */
export function detectSource(text: string): DetectedKind {
  const t = text.trim();
  if (!t) return "unknown";
  if (/^\s*services\s*:/m.test(t) && parseComposeDocument(t)) return "compose";
  if (looksLikeSql(t)) return "sql";
  if (looksLikeTree(t)) return "tree";
  return "unknown";
}

/** Converts text with a deterministic importer, or returns null when none applies (the caller may fall back to AI). */
export function convertSource(text: string): ImportResult | null {
  switch (detectSource(text)) {
    case "compose":
      return composeToImport(text);
    case "sql":
      return sqlToImport(text);
    case "tree":
      return treeToImport(text);
    default:
      return null;
  }
}

/**
 * Documentation for a diagram whose structure came from somewhere else (the AI): an overview, a
 * component table, the connections, and the groups.
 */
export function docFromGraph(graph: Graph, opts: { note?: string } = {}): string {
  const title = graph.title || "Architecture";
  const label = (id: string) => graph.nodes.find((n) => n.id === id)?.label ?? id;
  const out: string[] = [`# ${title}`, ""];
  out.push(`> ${opts.note ?? "Generated by Slate AI from the code you pasted."} Review it against the source before relying on it.`, "");
  out.push("## Components", "", table(["Component", "Details", "Group"], graph.nodes.map((n) => [code(n.label), n.subtitle, graph.groups.find((g) => g.id === n.group)?.label])), "");
  if (graph.kind === "sequence" && graph.messages?.length) {
    out.push("## Message flow", "");
    graph.messages.forEach((m, i) => out.push(`${i + 1}. ${code(label(m.from))} → ${code(label(m.to))}: ${m.label}`));
    out.push("");
  } else if (graph.edges.length) {
    out.push("## Connections", "");
    for (const e of graph.edges) out.push(`- ${code(label(e.from))} → ${code(label(e.to))}${e.label ? `: ${e.label}` : ""}${e.style === "dashed" ? " _(asynchronous)_" : ""}`);
    out.push("");
  }
  if (graph.groups.length) {
    out.push("## Boundaries", "");
    for (const g of graph.groups) {
      const members = graph.nodes.filter((n) => n.group === g.id).map((n) => code(n.label));
      out.push(`- **${g.label}**: ${members.join(", ") || "—"}`);
    }
    out.push("");
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

/** Wraps a model-produced graph as an ImportResult. */
export function aiImport(graph: Graph, warnings: string[]): ImportResult {
  const { graph: g } = normalizeGraph(graph);
  return { source: "ai", title: g.title || "Architecture", graph: g, markdown: docFromGraph(g), warnings };
}
